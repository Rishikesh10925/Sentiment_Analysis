import { BarChart3, BookOpen, Boxes, FlaskConical, ShieldAlert, Sparkles, Zap } from 'lucide-react'
import { api } from '../api/client'
import { useApi } from '../api/useApi'
import { ErrorState, LoadingState, Panel } from '../components/States'

function pct(value: unknown, digits = 1): string {
  return typeof value === 'number' ? `${(value * 100).toFixed(digits)}%` : '—'
}

function num(value: unknown, digits = 3): string {
  return typeof value === 'number' ? value.toFixed(digits) : '—'
}

function Stat({ label, value, sub }: { label: string; value: string; sub?: string }) {
  return (
    <div className="panel-soft p-3.5">
      <p className="eyebrow text-[7.5px]">{label}</p>
      <p className="mono mt-1.5 text-[21px] leading-none text-lime">{value}</p>
      {sub && <p className="mt-1.5 text-[9.5px] text-[var(--muted)]">{sub}</p>}
    </div>
  )
}

export function Research() {
  const research = useApi(api.research, [])

  if (research.loading) return <LoadingState label="Loading research artifacts" />
  if (research.error) return <ErrorState message={research.error} onRetry={research.reload} />
  const data = research.data
  if (!data) return <ErrorState message="Research artifact endpoint returned no data." />

  const baselines = (data.baselines ?? {}) as Record<string, any>
  const leaderboard = data.leaderboard ?? []
  const best = leaderboard[0]
  const transformer = (data.transformer ?? {}) as Record<string, any>
  const external = (data.external_roberta ?? {}) as Record<string, any>
  const absa = (data.absa ?? {}) as Record<string, any>
  const spark = data.spark_benchmark
  const domain = baselines.domain_shift ?? {}
  const ablations = baselines.ablations ?? []
  const errorExamples = baselines.error_examples ?? []
  const sparkRuns = spark?.runs ?? []
  const sparkLargestRows = Math.max(0, ...sparkRuns.map((run) => run.rows))
  const sparkTop = sparkRuns.find((run) => run.rows === sparkLargestRows && run.method === 'optimized')

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <p className="eyebrow">Reproducible evidence</p>
          <h1 className="mt-1 text-[30px] leading-tight">Research &amp; limitations</h1>
          <p className="mt-1 max-w-2xl text-[12.5px] leading-relaxed text-[var(--muted)]">
            Numbers below are generated by the scripts in this repository, not copied from papers.
            The dashboard uses the CPU linear model; stronger transformer results are reported separately.
          </p>
        </div>
        <span className="chip" style={{ color: 'var(--lime)' }}>
          <FlaskConical size={11} /> seed 42
        </span>
      </div>

      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="Best linear macro-F1" value={num(best?.macro_f1)} sub={`${best?.model ?? '—'} on TweetEval test`} />
        <Stat
          label="Fine-tuned transformer"
          value={num(transformer.macro_f1)}
          sub={transformer.device ? `${transformer.device.toUpperCase()} · DistilBERT` : 'artifact unavailable'}
        />
        <Stat
          label="Zero-shot RoBERTa"
          value={num(external.macro_f1)}
          sub="CardiffNLP checkpoint · external"
        />
        <Stat
          label="Spark speed-up"
          value={sparkTop?.speedup_vs_naive != null ? `${sparkTop.speedup_vs_naive}×` : '—'}
          sub={`optimized vs naive at ${(sparkLargestRows / 1_000_000).toFixed(1)}M rows`}
        />
      </div>

      <div className="grid gap-4 xl:grid-cols-[1.25fr_0.75fr]">
        <Panel title="Leaderboard" eyebrow="TweetEval sentiment · official test split">
          <div className="overflow-x-auto">
            <table className="w-full min-w-[560px]">
              <thead>
                <tr className="border-b text-left text-[8.5px] uppercase tracking-wider text-[var(--muted-2)]" style={{ borderColor: 'var(--line-soft)' }}>
                  <th className="px-4 py-2.5 font-medium">Model</th>
                  <th className="px-3 py-2.5 font-medium">Macro-F1</th>
                  <th className="px-3 py-2.5 font-medium">95% CI</th>
                  <th className="px-3 py-2.5 font-medium">Accuracy</th>
                  <th className="px-3 py-2.5 font-medium">ECE</th>
                </tr>
              </thead>
              <tbody>
                {leaderboard.map((row, index) => (
                  <tr key={row.model} className="border-b text-[11.5px]" style={{ borderColor: 'var(--line-soft)' }}>
                    <td className="px-4 py-2.5">
                      <span className="mono mr-2 text-[9px] text-[var(--muted-2)]">{String(index + 1).padStart(2, '0')}</span>
                      {row.model}
                      {index === 0 && <span className="ml-2 rounded bg-lime/10 px-1.5 py-0.5 text-[8px] font-semibold text-lime">BEST</span>}
                    </td>
                    <td className="mono px-3 py-2.5">{num(row.macro_f1)}</td>
                    <td className="mono px-3 py-2.5 text-[9.5px] text-[var(--muted)]">
                      {row.macro_f1_ci ? `${num(row.macro_f1_ci.ci95_low)}–${num(row.macro_f1_ci.ci95_high)}` : '—'}
                    </td>
                    <td className="mono px-3 py-2.5">{num(row.accuracy)}</td>
                    <td className="mono px-3 py-2.5">{row.ece != null ? num(row.ece) : '—'}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <p className="px-4 py-3 text-[9.5px] leading-relaxed text-[var(--muted-2)]">
            Majority-class macro-F1 is {num((baselines.majority as any)?.macro_f1)} — a reminder that accuracy alone is misleading on this class-imbalanced benchmark.
          </p>
        </Panel>

        <Panel title="What is measured" eyebrow="Method">
          <div className="space-y-4 p-4">
            {[
              ['Corpus', '1.65M real public posts (Sentiment140 + GoEmotions raw) with model-scored labels; gold labels retained only for evaluation.'],
              ['Benchmark', 'TweetEval sentiment: 45,615 train / 12,284 test, human labels, three classes.'],
              ['Serving choice', 'Word 1–2 gram TF-IDF + class-weighted logistic regression, selected for CPU latency and exact linear SHAP.'],
              ['Statistics', '1000-sample bootstrap CIs, expected calibration error, confusion matrices and explicit error examples.'],
            ].map(([label, text]) => (
              <div key={label}>
                <p className="eyebrow text-[7.5px]">{label}</p>
                <p className="mt-1 text-[11px] leading-relaxed text-[var(--muted)]">{text}</p>
              </div>
            ))}
          </div>
        </Panel>
      </div>

      <div className="grid gap-4 lg:grid-cols-3">
        <Panel title="Ablations" eyebrow="Same data, one change">
          <div className="space-y-3 p-4">
            {ablations.map((row: { name: string; variant: string; delta_macro_f1: number }) => (
              <div key={row.name} className="flex items-start justify-between gap-3 border-b pb-3 last:border-0 last:pb-0" style={{ borderColor: 'var(--line-soft)' }}>
                <div>
                  <p className="text-[11px] font-medium">{row.variant}</p>
                  <p className="mt-0.5 text-[9.5px] text-[var(--muted-2)]">vs {row.name.replace('_', ' ')}</p>
                </div>
                <span
                  className="mono text-[12px]"
                  style={{ color: row.delta_macro_f1 >= 0 ? 'var(--positive)' : 'var(--negative)' }}
                >
                  {row.delta_macro_f1 >= 0 ? '+' : ''}{row.delta_macro_f1.toFixed(4)}
                </span>
              </div>
            ))}
            {!ablations.length && <p className="text-[11px] text-[var(--muted)]">No ablation artifact.</p>}
          </div>
        </Panel>

        <Panel title="Domain shift" eyebrow="Out-of-benchmark behaviour">
          <div className="space-y-3 p-4">
            {Object.entries(domain).map(([name, rawValues]) => {
              const values = rawValues as Record<string, number>
              return (
                <div key={name} className="panel-soft p-3">
                  <div className="flex items-center justify-between">
                    <p className="text-[11.5px] font-semibold">{name}</p>
                    <span className="mono text-[10px] text-[var(--muted)]">n={Number(values.n ?? 0).toLocaleString()}</span>
                  </div>
                  <div className="mt-2 grid grid-cols-3 gap-2 text-center">
                    <div><p className="mono text-[13px] text-lime">{pct(values.neutral_prediction_rate)}</p><p className="text-[8px] text-[var(--muted-2)]">neutral rate</p></div>
                    <div><p className="mono text-[13px]">{pct(values.coverage_binary)}</p><p className="text-[8px] text-[var(--muted-2)]">coverage</p></div>
                    <div><p className="mono text-[13px]">{pct(values.binary_accuracy_on_covered)}</p><p className="text-[8px] text-[var(--muted-2)]">binary acc.</p></div>
                  </div>
                </div>
              )
            })}
            {!Object.keys(domain).length && <p className="text-[11px] text-[var(--muted)]">No domain-shift artifact.</p>}
          </div>
        </Panel>

        <Panel title="Learning curve" eyebrow="Label efficiency">
          <div className="space-y-4 p-4">
            {(baselines.learning_curve ?? []).map((row: { train_rows: number; macro_f1: number }) => (
              <div key={row.train_rows}>
                <div className="flex justify-between text-[10px]">
                  <span>{row.train_rows.toLocaleString()} rows</span>
                  <span className="mono">{row.macro_f1.toFixed(4)}</span>
                </div>
                <div className="mt-1 h-1.5 overflow-hidden rounded" style={{ background: 'var(--line)' }}>
                  <div className="h-full rounded bg-[var(--lime)]" style={{ width: `${(row.macro_f1 / 0.7) * 100}%` }} />
                </div>
              </div>
            ))}
            <p className="text-[9px] leading-relaxed text-[var(--muted-2)]">
              Linear models plateau near 0.58 macro-F1; transformer fine-tuning is the next measured step, not an assumed gain.
            </p>
          </div>
        </Panel>
      </div>

      <div className="grid gap-4 xl:grid-cols-2">
        <Panel title="Spark scaling benchmark" eyebrow="Real 1.6M corpus">
          {sparkRuns.length ? (
            <div className="overflow-x-auto">
              <table className="w-full">
                <thead>
                  <tr className="border-b text-left text-[8.5px] uppercase tracking-wider text-[var(--muted-2)]" style={{ borderColor: 'var(--line-soft)' }}>
                    <th className="px-4 py-2.5 font-medium">Rows</th>
                    <th className="px-3 py-2.5 font-medium">Method</th>
                    <th className="px-3 py-2.5 font-medium">Seconds</th>
                    <th className="px-3 py-2.5 font-medium">Rows/s</th>
                    <th className="px-3 py-2.5 font-medium">Speed-up</th>
                  </tr>
                </thead>
                <tbody>
                  {sparkRuns.map((run) => (
                    <tr key={`${run.rows}-${run.method}`} className="border-b text-[11px]" style={{ borderColor: 'var(--line-soft)' }}>
                      <td className="mono px-4 py-2.5">{run.rows.toLocaleString()}</td>
                      <td className="px-3 py-2.5">{run.method}</td>
                      <td className="mono px-3 py-2.5">{run.seconds.toFixed(2)}</td>
                      <td className="mono px-3 py-2.5">{Math.round(run.rows_per_second).toLocaleString()}</td>
                      <td className="mono px-3 py-2.5">{run.speedup_vs_naive ? `${run.speedup_vs_naive}×` : 'baseline'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
              <p className="px-4 py-3 text-[9px] leading-relaxed text-[var(--muted-2)]">
                Wall-clock on this machine only, median of repeated runs. Three arms compute the same aggregates:
                naive (Python UDF, AQE off, 200 shuffle partitions), native (same settings, SQL expressions), and
                optimized (pruning, AQE, partitions sized to cores). The partition sweep and the exact configuration
                are in the JSON artifact, so the tuning choice is auditable.
              </p>
            </div>
          ) : (
            <div className="p-4 text-[11px] text-[var(--muted)]">
              Benchmark artifact not present. Run <code className="mono">python -m research.benchmark</code>.
            </div>
          )}
        </Panel>

        <Panel title="Aspect-based sentiment" eyebrow="SemEval-2014 Task 4">
          <div className="p-4">
            {absa.available || absa.models ? (
              <div>
                <div className="grid grid-cols-3 gap-2">
                  <Stat label="Restaurants F1" value={num(absa.restaurants?.macro_f1 ?? absa.restaurant_macro_f1)} />
                  <Stat label="Laptops F1" value={num(absa.laptops?.macro_f1 ?? absa.laptop_macro_f1)} />
                  <Stat label="Aspect terms" value={String(absa.aspect_terms ?? absa.n_aspect_terms ?? '—')} />
                </div>
                <p className="mt-3 text-[9.5px] leading-relaxed text-[var(--muted-2)]">
                  Aspect-term classification uses sentence context; it is separate from document-level dashboard labels.
                </p>
              </div>
            ) : (
              <div className="flex min-h-[120px] flex-col items-center justify-center text-center">
                <Boxes size={18} className="text-[var(--muted)]" />
                <p className="mt-2 text-[11px] font-semibold">Not yet measured</p>
                <p className="mt-1 max-w-[270px] text-[10px] leading-relaxed text-[var(--muted)]">
                  The SemEval XML data is downloaded; the ABSA training run and artifact are still pending.
                </p>
              </div>
            )}
          </div>
        </Panel>
      </div>

      <div className="grid gap-4 xl:grid-cols-[1fr_0.8fr]">
        <Panel title="Failure modes" eyebrow="High-confidence errors">
          <div className="divide-y" style={{ borderColor: 'var(--line-soft)' }}>
            {errorExamples.slice(0, 6).map((row: { text: string; gold: string; predicted: string; confidence: number }, index: number) => (
              <div key={index} className="px-4 py-3">
                <p className="text-[11px] leading-relaxed">{row.text}</p>
                <p className="mt-1.5 text-[9px] text-[var(--muted-2)]">
                  gold <span className="text-[var(--text)]">{row.gold}</span> · predicted{' '}
                  <span className="text-negative">{row.predicted}</span> ·{' '}
                  <span className="mono">{pct(row.confidence)}</span>
                </p>
              </div>
            ))}
            {!errorExamples.length && <p className="p-4 text-[11px] text-[var(--muted)]">No error artifact.</p>}
          </div>
        </Panel>

        <Panel title="Limitations" eyebrow="Read before citing">
          <div className="space-y-3 p-4">
            {data.limitations.map((item) => (
              <div key={item} className="flex gap-2.5">
                <ShieldAlert size={13} className="mt-0.5 shrink-0 text-[var(--amber)]" />
                <p className="text-[10.5px] leading-relaxed text-[var(--muted)]">{item}</p>
              </div>
            ))}
          </div>
        </Panel>
      </div>

      <Panel title="Data provenance" eyebrow="Every source is public">
        <div className="grid gap-3 p-4 md:grid-cols-3">
          {(data.provenance.sources ?? []).map((source) => (
            <a
              key={source.name}
              href={source.url}
              target="_blank"
              rel="noreferrer"
              className="panel-soft group p-3 transition-colors hover:border-[color-mix(in_srgb,var(--lime)_30%,var(--line))]"
            >
              <div className="flex items-center justify-between">
                <p className="text-[11.5px] font-semibold">{source.name}</p>
                <BookOpen size={12} className="text-[var(--muted)] group-hover:text-lime" />
              </div>
              <p className="mt-1.5 text-[9.5px] leading-relaxed text-[var(--muted)]">{source.citation}</p>
            </a>
          ))}
        </div>
        <div className="flex flex-wrap items-center gap-4 border-t px-4 py-3 text-[9.5px] text-[var(--muted-2)]" style={{ borderColor: 'var(--line-soft)' }}>
          <span className="inline-flex items-center gap-1"><BarChart3 size={11} /> {Number(data.provenance.rows ?? 0).toLocaleString()} rows</span>
          <span className="inline-flex items-center gap-1"><Zap size={11} /> generated {data.provenance.generated_at?.slice(0, 10) ?? '—'}</span>
          <span className="inline-flex items-center gap-1"><Sparkles size={11} /> predictions, not gold labels</span>
        </div>
      </Panel>
    </div>
  )
}
